import { CASES, FIELDS, type Case, type Field, type GoldValue } from "./cases";
import { consistency, percentile, summarize, type CaseScore, type Summary } from "./score";

/** Writes eval/REPORT.md (results) and eval/LABELS.md (the dataset, for reviewing gold answers). */

export type ModeResult = {
  label: string;
  /** One array of case scores per repeat. */
  runs: CaseScore[][];
  latencies: number[];
  costs: number[];
  tokens: { input: number; output: number }[];
  dropped: number;
  missing: number;
};

export type ReportMeta = {
  date: string;
  model: string;
  promptVersion: string;
  datasetHash: string;
  imageDetail: string;
  repeats: number;
  pricing: { input: number; output: number; asOf: string };
};

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const money = (x: number) => (x < 0.01 ? `$${x.toFixed(4)}` : `$${x.toFixed(2)}`);
const ms = (x: number | null) => (x === null ? "–" : x < 1000 ? `${Math.round(x)} ms` : `${(x / 1000).toFixed(1)} s`);
const mean = (xs: number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);

function range(xs: number[], fmt: (x: number) => string): string {
  if (xs.length < 2) return fmt(xs[0] ?? 0);
  const lo = Math.min(...xs);
  const hi = Math.max(...xs);
  return lo === hi ? fmt(lo) : `${fmt(mean(xs))} (${fmt(lo)}–${fmt(hi)})`;
}

function filterRuns(runs: CaseScore[][], ids: Set<string>) {
  return runs.map((r) => r.filter((s) => ids.has(s.id)));
}

function summaries(cases: Case[], runs: CaseScore[][]): Summary[] {
  return runs.map((r) => summarize(cases, r));
}

function headlineRow(label: string, cases: Case[], mode: ModeResult | null, runs: CaseScore[][]) {
  if (!runs.length || !runs[0]!.length) return `| ${label} | not run | | | | | | |`;
  const s = summaries(cases, runs);
  const first = s[0]!;
  const injection = first.injection.total
    ? range(s.map((x) => x.injection.held / x.injection.total), pct) + ` of ${first.injection.total}`
    : "–";
  const exact = range(s.map((x) => x.exactCases / x.cases), pct) + ` of ${first.cases}`;
  const latency = mode && mode.latencies.length ? `${ms(percentile(mode.latencies, 50))} / ${ms(percentile(mode.latencies, 95))}` : "< 1 ms";
  const cost = mode && mode.costs.length ? money(mean(mode.costs) * 1000) : "$0";
  return `| ${label} | ${range(s.map((x) => x.accuracy), pct)} | ${range(s.map((x) => x.hallucinationRate), pct)} | ${range(
    s.map((x) => x.missRate),
    pct
  )} | ${exact} | ${injection} | ${latency} | ${cost} |`;
}

function goldText(g: GoldValue): string {
  if (g === null) return "∅";
  if (typeof g === "object") return g.anyOf.map((v) => (v === null ? "∅" : String(v))).join(" or ");
  return String(g);
}

function errorRows(label: string, runs: CaseScore[][]): string[] {
  const rows: string[] = [];
  const byCase = new Map<string, CaseScore[]>();
  for (const run of runs) for (const s of run) byCase.set(s.id, [...(byCase.get(s.id) ?? []), s]);
  for (const c of CASES) {
    const scores = byCase.get(c.id);
    if (!scores) continue;
    for (const f of FIELDS) {
      const bad = scores.filter((s) => s.outcomes[f] !== "correct" && s.outcomes[f] !== "correct_null");
      if (!bad.length) continue;
      const got = [...new Set(bad.map((s) => `${s.predicted[f] ?? "∅"} (${s.outcomes[f]})`))].join("; ");
      const runsNote = scores.length > 1 ? ` ${bad.length}/${scores.length} runs` : "";
      rows.push(`| ${label} | ${c.id} (${c.split}) | ${f} | ${goldText(c.gold[f])} | ${got}${runsNote} |`);
    }
  }
  return rows;
}

export function buildReport(meta: ReportMeta, parser: ModeResult, text: ModeResult, screen: ModeResult): string {
  const test = CASES.filter((c) => c.split === "test");
  const testIds = new Set(test.map((c) => c.id));
  const paired = CASES.filter((c) => c.screenshot);
  const pairedIds = new Set(paired.map((c) => c.id));
  const pairedTest = paired.filter((c) => c.split === "test");
  const pairedTestIds = new Set(pairedTest.map((c) => c.id));

  const head =
    "| Extractor | Field accuracy | Hallucination rate | Miss rate | Exact cases | Injection held | Latency p50 / p95 | Cost per 1,000 |\n" +
    "|---|---|---|---|---|---|---|---|";

  const lines: string[] = [];
  lines.push("# Extraction benchmark");
  lines.push("");
  lines.push(
    "How well Corral's autofill reads rental listings, measured on a labeled dataset of fictional IV/Goleta listings. " +
      "Generated by `npm run eval` from `eval/cases.ts`; see [`eval/README.md`](README.md) for the method."
  );
  lines.push("");
  lines.push(`- **Run:** ${meta.date} · model \`${meta.model}\` · prompt \`${meta.promptVersion}\` · dataset \`${meta.datasetHash}\``);
  lines.push(
    `- **Cases:** ${CASES.length} text listings (${test.length} held-out test, ${CASES.length - test.length} dev), ${paired.length} of them also as phone screenshots (${pairedTest.length} test)`
  );
  lines.push(
    `- **AI runs:** ${meta.repeats} repeats per case (the model isn't deterministic; ranges show min–max) · screenshots at \`${meta.imageDetail}\` detail`
  );
  lines.push(
    `- **Cost** is computed from the tokens the API reported, at $${meta.pricing.input} / $${meta.pricing.output} per million input / output tokens (${meta.pricing.asOf}).`
  );
  lines.push("");
  lines.push("**Reading the numbers:** *field accuracy* counts every scored field (address, link, rent, beds, baths, lease start and end, parking, laundry), including correctly left-empty ones. *Hallucination rate* is the share of fields the listing doesn't state that the extractor filled in anyway; *miss rate* is the share of stated fields it left empty. Counts are small, so a single field moves a percentage noticeably.");
  lines.push("");

  lines.push(`## Held-out test cases (${test.length} text, ${pairedTest.length} screenshots)`);
  lines.push("");
  lines.push(head);
  lines.push(headlineRow("Rule-based parser", test, null, filterRuns(parser.runs, testIds)));
  lines.push(headlineRow("AI · pasted text", test, text, filterRuns(text.runs, testIds)));
  lines.push(headlineRow("AI · screenshot", pairedTest, screen, filterRuns(screen.runs, pairedTestIds)));
  lines.push("");

  lines.push(`## All cases (${CASES.length} text, ${paired.length} screenshots)`);
  lines.push("");
  lines.push(head);
  lines.push(headlineRow("Rule-based parser", CASES, null, parser.runs));
  lines.push(headlineRow("AI · pasted text", CASES, text, text.runs));
  lines.push(headlineRow("AI · screenshot", paired, screen, screen.runs));
  lines.push("");
  lines.push("Latency and cost are per call across all cases; latency is measured from this machine with 4 calls in flight.");
  lines.push("");

  // Same listings, text vs. screenshot.
  lines.push(`## Text vs. screenshot on the same ${paired.length} listings`);
  lines.push("");
  const textPaired = filterRuns(text.runs, pairedIds);
  const pairedTextMode: ModeResult | null = text.runs.length ? text : null;
  lines.push(head);
  lines.push(headlineRow("AI · pasted text", paired, pairedTextMode, textPaired));
  lines.push(headlineRow("AI · screenshot", paired, screen, screen.runs));
  lines.push("");
  if (text.tokens.length && screen.tokens.length) {
    const tIn = mean(text.tokens.map((t) => t.input));
    const sIn = mean(screen.tokens.map((t) => t.input));
    const tOut = mean(text.tokens.map((t) => t.output));
    const sOut = mean(screen.tokens.map((t) => t.output));
    lines.push(
      `Average tokens per call: text ${Math.round(tIn)} in / ${Math.round(tOut)} out; screenshot ${Math.round(sIn)} in / ${Math.round(sOut)} out (output includes the model's reasoning).`
    );
    lines.push("");
  }

  // Per field.
  lines.push("## Accuracy by field (all cases)");
  lines.push("");
  lines.push("| Field | Parser | AI · text | AI · screenshot |");
  lines.push("|---|---|---|---|");
  const fieldCell = (cases: Case[], runs: CaseScore[][], f: Field) => {
    if (!runs.length || !runs[0]!.length) return "–";
    const s = summaries(cases, runs);
    return range(s.map((x) => x.perField[f].correct / x.perField[f].total), pct);
  };
  for (const f of FIELDS) {
    lines.push(`| ${f} | ${fieldCell(CASES, parser.runs, f)} | ${fieldCell(CASES, text.runs, f)} | ${fieldCell(paired, screen.runs, f)} |`);
  }
  lines.push("");

  // Reliability.
  lines.push("## Reliability");
  lines.push("");
  lines.push("| | AI · text | AI · screenshot |");
  lines.push("|---|---|---|");
  const fails = (m: ModeResult) => (m.runs.length ? `${m.runs.reduce((a, r) => a + r.filter((s) => s.failed).length, 0)} of ${m.runs.reduce((a, r) => a + r.length, 0)}` : "–");
  lines.push(`| Calls with no usable output (error, refusal, invalid JSON) | ${fails(text)} | ${fails(screen)} |`);
  lines.push(`| Fields dropped by the app's validator | ${text.dropped} | ${screen.dropped} |`);
  lines.push(`| Same answer on every repeat (case × field) | ${text.runs.length > 1 ? pct(consistency(text.runs)) : "–"} | ${screen.runs.length > 1 ? pct(consistency(screen.runs)) : "–"} |`);
  if (text.missing || screen.missing) lines.push(`| Calls not in the cache (counted as failures) | ${text.missing} | ${screen.missing} |`);
  lines.push("");

  // Every miss, for inspection.
  lines.push("## Every field that wasn't right");
  lines.push("");
  lines.push("∅ means empty. For AI rows, the run count shows how many repeats got it wrong.");
  lines.push("");
  lines.push("| Extractor | Case | Field | Expected | Got |");
  lines.push("|---|---|---|---|---|");
  const rows = [...errorRows("Parser", parser.runs), ...errorRows("AI text", text.runs), ...errorRows("AI screenshot", screen.runs)];
  lines.push(...(rows.length ? rows : ["| – | – | – | – | – |"]));
  lines.push("");
  return lines.join("\n");
}

export function buildLabels(): string {
  const lines = [
    "# Benchmark labels (for review)",
    "",
    "Every case in `eval/cases.ts` with its expected answers. ∅ means the listing doesn't clearly say, so the right answer is to leave the field empty; \"or\" lists every acceptable answer for an ambiguous listing. Generated by `npm run eval`.",
    ""
  ];
  for (const c of CASES) {
    lines.push(`## ${c.id} · ${c.format} · ${c.split}${c.screenshot ? ` · screenshot (${c.screenshot.template}${c.screenshot.variant ? `, ${c.screenshot.variant}` : ""})` : ""}`);
    lines.push("");
    lines.push("```text");
    lines.push(c.text);
    lines.push("```");
    lines.push("");
    lines.push(`| ${FIELDS.join(" | ")} |`);
    lines.push(`|${FIELDS.map(() => "---").join("|")}|`);
    lines.push(`| ${FIELDS.map((f) => goldText(c.gold[f]).replace(/\|/g, "\\|")).join(" | ")} |`);
    if (c.mustNot) lines.push(`\nInjected values that must not appear: ${Object.entries(c.mustNot).map(([f, v]) => `${f} = ${v}`).join(", ")}`);
    lines.push("");
  }
  return lines.join("\n");
}
